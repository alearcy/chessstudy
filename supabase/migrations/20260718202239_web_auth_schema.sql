create table public.user_settings (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  stockfish_depth smallint not null default 15 check (stockfish_depth between 1 and 30),
  stockfish_threads smallint not null default 2 check (stockfish_threads between 1 and 32),
  lichess_username text not null default '',
  chesscom_username text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.lessons (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  uid uuid not null default gen_random_uuid(),
  title text not null check (length(btrim(title)) > 0),
  description text not null default '',
  mode text not null default 'study' check (mode in ('study', 'analysis')),
  is_favorite boolean not null default false,
  search_text text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint lessons_id_user_unique unique (id, user_id),
  constraint lessons_user_uid_unique unique (user_id, uid)
);

create table public.boards (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  uid uuid not null default gen_random_uuid(),
  lesson_id bigint not null,
  title text not null check (length(btrim(title)) > 0),
  fen text not null check (length(btrim(fen)) > 0),
  notes text not null default '',
  arrows jsonb not null default '[]'::jsonb check (jsonb_typeof(arrows) = 'array'),
  highlights jsonb not null default '[]'::jsonb check (jsonb_typeof(highlights) = 'array'),
  board_order integer not null default 0 check (board_order >= 0),
  eval_cp integer,
  eval_mate integer,
  eval_depth smallint not null default 0 check (eval_depth between 0 and 30),
  eval_best_move_uci text,
  white_name text,
  black_name text,
  headers jsonb not null default '{}'::jsonb check (jsonb_typeof(headers) = 'object'),
  game_analysis text,
  opening_report jsonb,
  opening_eco text,
  opening_name text,
  opening_family text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint boards_id_user_unique unique (id, user_id),
  constraint boards_user_uid_unique unique (user_id, uid),
  constraint boards_lesson_order_unique unique (lesson_id, board_order),
  constraint boards_lesson_owner_fkey
    foreign key (lesson_id, user_id)
    references public.lessons (id, user_id)
    on delete cascade
);

create table public.moves (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  uid uuid not null default gen_random_uuid(),
  board_id bigint not null,
  parent_id bigint,
  move_notation text not null check (length(btrim(move_notation)) > 0),
  fen text not null check (length(btrim(fen)) > 0),
  move_order integer not null check (move_order >= 0),
  comment text not null default '',
  analysis_comment text,
  stockfish_comment text,
  arrows jsonb not null default '[]'::jsonb check (jsonb_typeof(arrows) = 'array'),
  highlights jsonb not null default '[]'::jsonb check (jsonb_typeof(highlights) = 'array'),
  eval_cp integer,
  eval_mate integer,
  eval_depth smallint not null default 0 check (eval_depth between 0 and 30),
  eval_best_move_uci text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint moves_id_board_user_unique unique (id, board_id, user_id),
  constraint moves_user_uid_unique unique (user_id, uid),
  constraint moves_board_order_unique unique (board_id, move_order),
  constraint moves_parent_not_self check (parent_id is null or parent_id <> id),
  constraint moves_board_owner_fkey
    foreign key (board_id, user_id)
    references public.boards (id, user_id)
    on delete cascade,
  constraint moves_parent_board_owner_fkey
    foreign key (parent_id, board_id, user_id)
    references public.moves (id, board_id, user_id)
    deferrable initially deferred
);

create index lessons_user_created_idx
  on public.lessons (user_id, created_at desc, id desc);
create index lessons_user_mode_created_idx
  on public.lessons (user_id, mode, created_at desc, id desc);
create index lessons_user_favorite_created_idx
  on public.lessons (user_id, created_at desc, id desc)
  where is_favorite;
create index lessons_search_idx
  on public.lessons using gin (to_tsvector('simple', search_text));
create index boards_lesson_id_idx
  on public.boards (lesson_id, user_id, board_order);
create index moves_board_id_idx
  on public.moves (board_id, user_id, move_order);
create index moves_parent_id_idx
  on public.moves (parent_id, board_id, user_id)
  where parent_id is not null;

